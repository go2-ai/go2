require "rails_helper"

RSpec.describe Accounting::JournalEntries::LockGuard do
  let(:organization) { create(:organization) }
  let(:ledger) do
    create(:accounting_ledger, account_category: organization.account_categories.find_by!(identifier: "CA"), code: "10")
  end
  let(:account) { create(:accounting_account, ledger: ledger, code: "01", name: { en: "Cash" }) }

  let(:fiscal_year) do
    create(:fiscal_year, organization: organization,
           start_date: Date.new(2024, 1, 1), finish_date: Date.new(2024, 12, 31))
  end
  let(:next_fiscal_year) do
    create(:fiscal_year, organization: organization,
           start_date: Date.new(2025, 1, 1), finish_date: Date.new(2025, 12, 31))
  end

  def build_entry(fy: fiscal_year, state: :booked, date: fy.start_date, **attrs)
    entry = build(:accounting_journal_entry, organization: organization, fiscal_year: fy,
                  date: date, state: state, **attrs)
    entry.items.build(row: 1, account: account, debit: 100, credit: 0, rate: nil)
    entry.items.build(row: 2, account: account, debit: 0, credit: 100, rate: nil)
    entry
  end

  def create_entry(...)
    build_entry(...).tap(&:save!)
  end

  describe "entries created by users" do
    it "are allowed in open fiscal years" do
      entry = build_entry
      expect(entry).to be_valid
      expect(entry.lock_reason).to be_nil
    end

    %w[closing closed].each do |status|
      context "when the fiscal year is #{status}" do
        let!(:entry) { create_entry }

        before { fiscal_year.update_column(:status, FiscalYear.statuses[status]) }

        it "can't be created" do
          new_entry = build_entry
          expect(new_entry).not_to be_valid
          expect(new_entry.errors[:base].join).to include("Fiscal year")
        end

        it "can't be updated" do
          entry.reload
          expect(entry.update(description: "changed")).to be(false)
        end

        it "can't be approved or unapproved" do
          entry.reload
          expect(entry.approve(nil)).to be(false)
          entry.update_column(:state, Accounting::JournalEntry.states[:approved])
          expect(entry.reload.unapprove).to be(false)
        end

        it "can't be destroyed" do
          entry.reload
          expect(entry.destroy).to be(false)
          expect(Accounting::JournalEntry.exists?(entry.id)).to be(true)
        end

        it "report why they are locked" do
          expect(entry.reload.lock_reason).to include("Fiscal year")
        end
      end
    end

    it "can't be moved out of a closed fiscal year into an open one" do
      entry = create_entry
      fiscal_year.update_column(:status, FiscalYear.statuses[:closed])
      entry.reload
      entry.fiscal_year = next_fiscal_year
      entry.date = next_fiscal_year.start_date
      expect(entry).not_to be_valid
      expect(entry.errors[:base].join).to include("is closed")
    end

    it "can't be moved from an open fiscal year into a closing one" do
      entry = create_entry
      next_fiscal_year.update_column(:status, FiscalYear.statuses[:closing])
      entry.fiscal_year = next_fiscal_year
      entry.date = next_fiscal_year.start_date
      expect(entry).not_to be_valid
      expect(entry.errors[:base].join).to include("is being closed")
    end
  end

  describe "entries generated by the system" do
    let!(:entry) do
      create_entry(state: :approved, date: fiscal_year.finish_date, entry_type: :ending,
                   source: fiscal_year, system_context: :fiscal_year_closing)
    end

    it "can't be changed by users, even in open fiscal years" do
      # A fresh instance, as loaded by a controller (no system_context).
      loaded = Accounting::JournalEntry.find(entry.id)
      expect(loaded.lock_reason).to include("generated by the system")
      expect(loaded.update(description: "changed")).to be(false)
      expect(loaded.unapprove).to be(false)
      expect(loaded.destroy).to be(false)
      expect(Accounting::JournalEntry.exists?(entry.id)).to be(true)
    end

    it "can be changed and destroyed by system services in closing fiscal years" do
      fiscal_year.update_column(:status, FiscalYear.statuses[:closing])
      entry.reload
      entry.system_context = :fiscal_year_closing
      expect(entry.update(description: "changed")).to be(true)
      expect(entry.destroy).to be_truthy
    end

    it "can't be changed by system services in closed fiscal years" do
      fiscal_year.update_column(:status, FiscalYear.statuses[:closed])
      entry.reload
      entry.system_context = :fiscal_year_closing
      expect(entry.destroy).to be(false)
      expect(entry.errors[:base].join).to include("is closed")
    end

    it "can be created by system services in closing fiscal years" do
      fiscal_year.update_column(:status, FiscalYear.statuses[:closing])
      new_entry = build_entry(state: :approved, date: fiscal_year.finish_date, entry_type: :closing_temp_accounts,
                              source: fiscal_year, system_context: :fiscal_year_closing)
      expect(new_entry).to be_valid
    end
  end
end
