require "rails_helper"

RSpec.describe Accounting::Balances::Query do
  let(:organization) { create(:organization) }
  let(:usd) { organization.accounting_setting.main_currency }
  let(:eur) { create(:accounting_currency, organization: organization, abr: "EUR") }
  let(:fiscal_year) do
    create(:fiscal_year, organization: organization,
           start_date: Date.new(2024, 1, 1), finish_date: Date.new(2024, 12, 31))
  end

  let(:bank) { create_account_in(organization, "CA", ledger_code: "10", monetary: true, name: "Bank") }
  let(:inventory) { create_account_in(organization, "CA", ledger_code: "20", name: "Inventory") }
  let(:payable) { create_account_in(organization, "CL", ledger_code: "10", monetary: true, name: "Payable") }
  let(:revenue) { create_account_in(organization, "RE", ledger_code: "10", name: "Sales") }

  let(:center_type) do
    create(:accounting_center_type, organization: organization, first_code: "000001", last_code: "000050")
  end
  let(:branch_a) { create(:accounting_center, center_type: center_type, code: "000001") }
  let(:branch_b) { create(:accounting_center, center_type: center_type, code: "000002") }

  def query(**options)
    described_class.new(organization: organization, fiscal_year: fiscal_year, **options).call
  end

  def row_for(rows, account, currency, centers = [])
    center_ids = Array.new(6) { |i| centers[i]&.id }
    rows.find { |r| r.key == [ account.id, *center_ids, currency.id ] }
  end

  before do
    # EUR sale on branch A: 100 EUR at 1.1 (debit bank 110 USD).
    post_entry(fiscal_year: fiscal_year, date: Date.new(2024, 3, 1), lines: [
      je_line(bank, debit: 110, currency: eur, rate: 1.1, centers: { 1 => branch_a }),
      je_line(revenue, credit: 110, centers: { 1 => branch_a })
    ])
    # Paying 40 EUR at 1.2 from the bank on branch A (credit bank 48 USD).
    post_entry(fiscal_year: fiscal_year, date: Date.new(2024, 6, 1), lines: [
      je_line(payable, debit: 48),
      je_line(bank, credit: 48, currency: eur, rate: 1.2, centers: { 1 => branch_a })
    ])
    # USD sale on branch B.
    post_entry(fiscal_year: fiscal_year, date: Date.new(2024, 9, 1), lines: [
      je_line(bank, debit: 300, centers: { 1 => branch_b }),
      je_line(revenue, credit: 300, centers: { 1 => branch_b })
    ])
    # Drafts are not part of balances.
    post_entry(fiscal_year: fiscal_year, date: Date.new(2024, 9, 2), state: :draft, lines: [
      je_line(bank, debit: 999),
      je_line(revenue, credit: 999)
    ])
  end

  it "groups by account, centers and currency with signed base and foreign balances" do
    rows = query

    eur_bank = row_for(rows, bank, eur, [ branch_a ])
    expect(eur_bank.debit).to eq(110)
    expect(eur_bank.credit).to eq(48)
    expect(eur_bank.base_balance).to eq(62)
    expect(eur_bank.currency_balance).to eq(60)

    usd_bank = row_for(rows, bank, usd, [ branch_b ])
    expect(usd_bank.base_balance).to eq(300)
    expect(usd_bank.currency_balance).to eq(300)

    expect(row_for(rows, revenue, usd, [ branch_a ]).base_balance).to eq(-110)
    expect(row_for(rows, payable, usd).base_balance).to eq(48)
    expect(rows.map(&:base_balance)).to all(be_a(BigDecimal))
  end

  it "excludes drafts" do
    expect(row_for(query, bank, usd)).to be_nil
  end

  it "includes only entries dated on or before as_of" do
    rows = query(as_of: Date.new(2024, 5, 31))
    expect(row_for(rows, bank, eur, [ branch_a ]).currency_balance).to eq(100)
    expect(row_for(rows, bank, usd, [ branch_b ])).to be_nil
  end

  it "filters by monetary ledgers and foreign currencies" do
    rows = query(monetary_only: true, foreign_only: true)
    expect(rows.map { |r| [ r.account_id, r.currency_id ] }).to eq([ [ bank.id, eur.id ] ])
  end

  it "filters by category type" do
    rows = query(category_types: %w[income_statement])
    expect(rows.map(&:account_id).uniq).to eq([ revenue.id ])
  end

  it "filters by centers and accounts" do
    expect(query(center1_ids: [ branch_b.id ]).map(&:account_id)).to contain_exactly(bank.id, revenue.id)
    expect(query(account_ids: [ payable.id ]).size).to eq(1)
  end

  it "can limit to approved entries" do
    post_entry(fiscal_year: fiscal_year, date: Date.new(2024, 10, 1), state: :booked, lines: [
      je_line(inventory, debit: 5),
      je_line(payable, credit: 5)
    ])
    expect(row_for(query, inventory, usd)).to be_present
    expect(row_for(query(states: %w[approved]), inventory, usd)).to be_nil
  end

  it "ignores entries generated by excluded sources" do
    post_entry(fiscal_year: fiscal_year, date: Date.new(2024, 12, 31), entry_type: :ending,
               source: fiscal_year, system_context: :fiscal_year_closing, lines: [
                 je_line(payable, credit: 48)
               ] + [ je_line(inventory, debit: 48) ])

    expect(row_for(query, inventory, usd).base_balance).to eq(48)
    expect(row_for(query(exclude_sources: [ fiscal_year ]), inventory, usd)).to be_nil
    # Entries without a source are kept.
    expect(row_for(query(exclude_sources: [ fiscal_year ]), payable, usd).base_balance).to eq(48)
  end

  it "skips combinations whose balances are zero unless asked" do
    post_entry(fiscal_year: fiscal_year, date: Date.new(2024, 11, 1), lines: [
      je_line(inventory, debit: 10), je_line(inventory, credit: 10)
    ])
    expect(row_for(query, inventory, usd)).to be_nil
    expect(row_for(query(include_zero: true), inventory, usd)).to be_present
  end

  it "keeps foreign balances when a revaluation line has no currency amount" do
    post_entry(fiscal_year: fiscal_year, date: Date.new(2024, 12, 31), entry_type: :revaluation,
               source: fiscal_year, system_context: :currency_revaluation, lines: [
                 je_line(bank, debit: 10, currency: eur, rate: 1.2, currency_amount: 0, centers: { 1 => branch_a }),
                 je_line(revenue, credit: 10)
               ])
    eur_bank = row_for(query, bank, eur, [ branch_a ])
    expect(eur_bank.base_balance).to eq(72)
    expect(eur_bank.currency_balance).to eq(60)
  end

  it "rejects unknown filters" do
    expect { query(colour_ids: [ 1 ]) }.to raise_error(ArgumentError, /colour_ids/)
  end
end
