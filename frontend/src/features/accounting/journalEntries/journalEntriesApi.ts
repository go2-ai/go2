import { createApi } from '@reduxjs/toolkit/query/react';
import { baseQueryWithCsrf } from '../../../app/baseQuery';

export interface JournalEntryItem {
  id: number;
  row: number;
  account_id: number | null;
  center1_id: number | null;
  center2_id: number | null;
  center3_id: number | null;
  center4_id: number | null;
  center5_id: number | null;
  center6_id: number | null;
  debit: number;
  credit: number;
  currency_id: number;
  rate: number;
  currency_amount: number;
  account_code?: string;
  account_name?: string;
  t?: {
    description?: Record<string, string>;
  };
}

export type JournalEntryType =
  | 'normal'
  | 'beginning'
  | 'revaluation'
  | 'closing_temp_accounts'
  | 'ending';

export interface JournalEntry {
  id: number;
  date: string;
  effective_date: string;
  fiscal_year_id: number;
  no: string;
  ref: string;
  daily_no: number;
  state: 'draft' | 'booked' | 'approved';
  entry_type: JournalEntryType;
  debit: number;
  credit: number;
  organization_id: number;
  creator_id: number | null;
  created_at: string;
  creator_name: string;
  /** Record that generated the entry (revaluation, fiscal year closing); null for user entries. */
  source_type: string | null;
  source_id: number | null;
  /** True for entries generated by revaluation or fiscal year closing. */
  system_generated: boolean;
  /** Why users can't change the entry (closed fiscal year, system generated); null when they can. */
  lock_reason: string | null;
  approved_at: string | null;
  approved_by_id: number | null;
  approved_by_name: string | null;
  t?: {
    description?: Record<string, string>;
  };
  items: JournalEntryItem[];
}

